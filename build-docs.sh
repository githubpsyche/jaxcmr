#!/usr/bin/env bash
# Stage the book's selected notebooks and inputs, then render saved outputs.
set -euo pipefail
cd "$(dirname "$0")"

# These directories contain generated copies only; authoritative notebooks stay
# in templates/ and guide/. Keep chapter paths as plain list entries.
rm -rf -- guide/templates guide/downloads docs
mkdir -p guide/templates/data/fits guide/templates/data/simulations guide/downloads
notebooks=()
while IFS= read -r notebook; do
    notebooks+=("$notebook")
    cp "${notebook}" "guide/${notebook}"
    cp "$notebook" "guide/downloads/${notebook##*/}"
done < <(sed -nE 's/^[[:space:]]*-[[:space:]]+(templates\/[A-Za-z0-9_]+\.ipynb)[[:space:]]*$/\1/p' guide/_quarto.yml)
if [ "${#notebooks[@]}" -eq 0 ]; then
    printf 'No notebook chapters found in guide/_quarto.yml\n' >&2
    exit 1
fi

cp guide/developer-setup.ipynb guide/downloads/developer-setup.ipynb

# Library Guide sources live in the guide; only their downloadable copies are staged.
mkdir -p guide/downloads/overview
while IFS= read -r notebook; do
    cp "guide/$notebook" "guide/downloads/$notebook"
done < <(sed -nE 's/^[[:space:]]*-[[:space:]]+(overview\/[A-Za-z0-9_]+\.ipynb)[[:space:]]*$/\1/p' guide/_quarto.yml)

# One observation source and its existing matrix, shared by all chapters.
for asset in Dupertuys2026.h5 Dupertuys2026_semantic_distances.npy \
    fits/Dupertuys2026_CMR_demo.json fits/Dupertuys2026_eCMR_source_only.json \
    fits/Dupertuys2026_eCMR_broad.json fits/README.md; do
    cp "data/$asset" "guide/templates/data/$asset"
done

# Saved response examples are inputs to analyses, never regenerated by the book build.
for stem in Dupertuys2026_CMR_demo_best_of_3 Dupertuys2026_eCMR_source_only_demo_best_of_3 Dupertuys2026_eCMR_broad_demo_best_of_3; do
    cp "data/simulations/$stem.h5" "data/simulations/$stem.json" guide/templates/data/simulations/
done

quarto render guide --no-execute

touch docs/.nojekyll

printf 'Documentation rendered to docs/index.html\n'
